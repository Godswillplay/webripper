class WAFScanner(BaseScanner):
    """Detects Web Application Firewalls protecting the target."""

    @property
    def name(self) -> str:
        return "waf"

    @property
    def description(self) -> str:
        return "Detects Web Application Firewalls (WAFs) and suggests bypass techniques"

    def scan(self) -> ScanResult:
        start = time.time()
        self._log("Scanning for WAF presence...")

        detected: List[Tuple[str, int, str]] = []  # (name, confidence, bypass)

        # Phase 1: Passive detection from crawled response headers/cookies
        for waf in _WAF_SIGNATURES:
            conf = self._check_passive(waf)
            if conf > 0:
                detected.append((waf["name"], conf, waf["bypass"]))

        # Phase 2: Active detection — send suspicious request
        try:
            loop = asyncio.new_event_loop()
            asyncio.set_event_loop(loop)
            active_results = loop.run_until_complete(self._active_probe())
            loop.close()
            for waf_name, conf, bypass in active_results:
                # Merge with existing or add new
                existing = [d for d in detected if d[0] == waf_name]
                if existing:
                    idx = detected.index(existing[0])
                    detected[idx] = (waf_name, min(100, existing[0][1] + conf), bypass)
                else:
                    detected.append((waf_name, conf, bypass))
        except Exception as e:
            self._log(f"Active WAF probe error: {e}")

        # Create findings
        if detected:
            for waf_name, confidence, bypass in detected:
                sev = Severity.INFO if confidence < 50 else Severity.MEDIUM
                self._add_finding(Finding(
                    severity=sev,
                    category="waf",
                    title=f"WAF Detected: {waf_name}",
                    description=f"{waf_name} WAF detected with {confidence}% confidence. "
                                f"This affects scanning strategy and exploit feasibility.",
                    evidence=f"Confidence: {confidence}%",
                    remediation="WAF detection is informational. Ensure WAF rules are properly configured and updated.",
                    metadata={
                        "waf_name": waf_name,
                        "confidence": confidence,
                        "exploit": f"WAF bypass techniques for {waf_name}: {bypass}",
                        "impact": "WAF may block exploitation attempts, but bypasses exist. Attacker adjusts payloads to evade detection rules.",
                        "cwe": "CWE-693",
                        "owasp": "A05:2021 Security Misconfiguration",
                        "time_to_exploit": "~30 minutes to identify bypasses",
                    },
                ))
        else:
            self._add_finding(Finding(
                severity=Severity.LOW,
                category="waf",
                title="No WAF Detected",
                description="No Web Application Firewall was detected protecting this target. "
                            "The application is directly exposed to attacks.",
                remediation="Deploy a WAF (Cloudflare, AWS WAF, ModSecurity) to filter malicious traffic.",
                metadata={
                    "exploit": "Without WAF, all attack payloads reach the application directly. SQL injection, XSS, and other attacks are not filtered at the network edge.",
                    "impact": "All vulnerability exploitation attempts will reach the application unfiltered",
                    "cwe": "CWE-693",
                    "owasp": "A05:2021 Security Misconfiguration",
                    "time_to_exploit": "Immediate — no filtering layer",
                },
            ))

        self._log(f"WAF scan complete: {len(detected)} WAF(s) detected")
        return self._build_result(start, wafs_detected=len(detected))

    def _check_passive(self, waf: Dict) -> int:
        """Check crawled responses for WAF signatures. Returns confidence 0-100."""
        confidence = 0

        for f in self._report.files:
            if not f.response_headers:
                continue
            headers_lower = {k.lower(): v.lower() for k, v in f.response_headers.items()}

            # Check header patterns
            for header_key, pattern in waf.get("headers", {}).items():
                val = headers_lower.get(header_key, "")
                if val and (not pattern or pattern in val):
                    confidence += 40

            # Check cookie patterns
            cookie_header = headers_lower.get("set-cookie", "")
            for cookie_pat in waf.get("cookies", []):
                if cookie_pat.lower() in cookie_header:
                    confidence += 30

        return min(confidence, 95)

    async def _active_probe(self) -> List[Tuple[str, int, str]]:
        """Send a suspicious request to trigger WAF block pages."""
        results = []
        target = self._settings.url.rstrip("/")
        probe_url = f"{target}/?q=<script>alert(1)</script>&id=1' OR 1=1--"

        try:
            timeout = aiohttp.ClientTimeout(total=10)
            headers = self._build_headers()
            proxy = self._get_proxy()
            async with aiohttp.ClientSession(
                timeout=timeout,
                headers=headers,
                max_line_size=131072,
                max_field_size=131072,
            ) as session:
                async with session.get(probe_url, ssl=False, allow_redirects=False, proxy=proxy) as resp:
                    body = await resp.text(errors="ignore")
                    body_lower = body.lower()

                    for waf in _WAF_SIGNATURES:
                        for pattern in waf.get("body", []):
                            if pattern.lower() in body_lower:
                                results.append((waf["name"], 50, waf["bypass"]))
                                break

                    # Generic WAF detection
                    if resp.status in (403, 406, 429, 503):
                        headers_lower = {k.lower(): v.lower() for k, v in resp.headers.items()}
                        found_generic = False
                        for h in ("x-waf-", "x-firewall", "x-security", "cf-ray", "x-sucuri", "x-amz"):
                            for k in headers_lower:
                                if h in k:
                                    results.append(("Generic / Cloud WAF", 45, "WAF detected via response headers. Try encoding payloads with URL encoding, unicode, or base64."))
                                    found_generic = True
                                    break
                            if found_generic:
                                break
                        if not found_generic and not results and resp.status in (403, 406, 429):
                            results.append(("Behavioral Application Firewall / Filter", 35, f"Probe blocked with HTTP {resp.status}. Input filtering is active; test alternative character encodings and bypasses."))
        except Exception:
            pass

        return results
